type Clock = { month: number; day: number; hour: number; minute: number };

export type OfficialSolarTermYear = {
  year: number;
  sourceType: "kasi-almanac" | "kasi-calendar-data" | "kasi-calendar-data-preview";
  sourceReference: {
    publisher: "KASI";
    documentId: string;
    url: string;
    note: string;
  };
  directOfficial: boolean;
  terms: Record<SolarTermName, Clock>;
};

function clocks(rows: Array<[SolarTermName, number, number, number, number]>): Record<SolarTermName, Clock> {
  return Object.fromEntries(rows.map(([name, month, day, hour, minute]) => [name, { month, day, hour, minute }])) as Record<
    SolarTermName,
    Clock
  >;
}

