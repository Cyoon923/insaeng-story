/**
 * 약관·정책 버전 상수.
 *
 * 동의 증빙(User.consents)에 남길 버전 문자열을 한곳에서 정의한다.
 * 버전은 서버가 이 상수에서 채운다. 클라이언트가 보낸 값을 그대로 저장하면
 * 임의 문자열이 증빙에 남으므로 신뢰하지 않는다.
 *
 * 문서마다 버전을 따로 둔다. 세 문서는 목적도 개정 시점도 다르기 때문이다.
 * - TERMS_VERSION          /terms              이용약관
 * - SIGNUP_PRIVACY_VERSION /privacy/collection 회원가입 시 받는 [필수] 수집·이용 동의
 * - PRIVACY_POLICY_VERSION /privacy            상시 공개하는 개인정보 처리방침
 *
 * 회원가입 동의 증빙에 들어가는 것은 앞의 두 개다. 처리방침은 동의 대상이
 * 아니라 고지 문서라서 증빙에 쓰지 않는다.
 *
 * 네 문서의 시행일은 처음 2026-09-25로 확정되었으나, 이후 둘이 따로 개정되었다.
 * 지금은 이용약관(TERMS_VERSION)과 신청 단계 동의(ORDER_CONSENT_VERSION)만
 * LEGAL_EFFECTIVE_DATE를 함께 읽는다.
 *
 * 따로 관리하는 둘:
 * - SIGNUP_PRIVACY_VERSION  2026-09-26  소셜 간편가입에서 가입 시 휴대폰을 받지 않게 되었다.
 * - PRIVACY_POLICY_VERSION  2026-09-26  고지 항목(위탁·국외이전·파기·보호책임자)을 보강했다.
 *
 * 두 값의 날짜가 같아도 상수를 합치지 않는다. 한쪽이 다시 개정될 때 다른 쪽이
 * 따라 움직이면 안 되기 때문이다.
 *
 * 증빙을 만드는 코드(lib/server/consents.ts)가 이 상수들을 읽어 저장하므로,
 * 값을 바꾸면 그 뒤에 저장되는 동의부터 새 버전이 남는다.
 * 이미 저장된 증빙은 소급해 고치지 않는다.
 */

/**
 * 아직 확정되지 않은 버전임을 나타내는 값.
 * 확정 시행일로 교체하면 areLegalVersionsConfirmed()가 true가 된다.
 */
export const UNCONFIRMED_VERSION = "unconfirmed-draft";

/**
 * 네 문서의 확정 시행일(YYYY-MM-DD).
 *
 * 버전 문자열과 화면에 보여 주는 시행일이 같은 값이다. 두 곳에 따로 적으면
 * 증빙에 남은 버전과 고객이 본 날짜가 갈라질 수 있어 상수 하나에서 나온다.
 * 문서가 개정되면 이 값을 바꾸고, 그 뒤에 저장되는 동의부터 새 값이 남는다.
 * 이미 저장된 증빙은 그대로 둔다(소급해 고치지 않는다).
 */
// 타입을 string으로 두는 이유: 아래 gate가 UNCONFIRMED_VERSION과 비교한다.
// 리터럴 타입으로 좁혀지면 "겹치지 않는 비교"로 잡혀, 값을 되돌릴 수 없게 된다.
export const LEGAL_EFFECTIVE_DATE: string = "2026-09-25";

/** 이용약관(/terms) 버전. 확정 전 자리표시자. */
export const TERMS_VERSION = LEGAL_EFFECTIVE_DATE;

/**
 * 회원가입 개인정보 수집 및 이용 동의(/privacy/collection)의 **시행일**.
 *
 * 다른 세 문서와 달리 LEGAL_EFFECTIVE_DATE를 그대로 쓰지 않는다. 이 문서만 따로
 * 개정되기 때문이다. 소셜 간편가입에서 가입 시 휴대폰 번호를 받지 않게 되면서
 * 수집 시점과 범위가 실제로 달라졌고, 본문(/privacy/collection)도 그에 맞게 고쳤다.
 *
 * 개정 시행일은 2026-09-26으로 확정되었다. 다른 세 문서(2026-09-25)보다 하루 뒤다.
 * 그래서 개정 전 문서에 동의한 회원과 개정 후 문서에 동의한 회원의 증빙 버전이
 * 서로 다른 값으로 남는다. 이미 저장된 증빙은 소급해 고치지 않는다.
 *
 * 이 문서가 다시 개정되면 이 값만 바꾼다. 다른 세 축은 따라 움직이지 않는다.
 *
 * UNCONFIRMED_VERSION을 자리표시자로 두지 않는다. 아래 areLegalVersionsConfirmed()가
 * 이 값을 보고, 그 관문이 소셜 가입뿐 아니라 **아이디·비밀번호 가입까지** 503으로 막는다
 * (api/app의 signupComplete / completeSocialLink / completeSocialSignup 세 곳).
 * 배포일을 정하기 전에 가입 자체를 세우는 편이 더 나쁘다.
 *
 * 타입을 string으로 두는 이유는 LEGAL_EFFECTIVE_DATE와 같다. 리터럴로 좁혀지면
 * 아래 gate의 UNCONFIRMED_VERSION 비교가 "겹치지 않는 비교"로 잡힌다.
 */
export const SIGNUP_PRIVACY_VERSION: string = "2026-09-26";

/**
 * 개인정보 처리방침(/privacy)의 **시행일**.
 *
 * LEGAL_EFFECTIVE_DATE를 그대로 쓰지 않는다. 이 문서만 따로 개정되었기 때문이다.
 * 처리·위탁 현황, 국외 이전, 파기 절차, 보호책임자 같은 고지 항목을 실제 운영에 맞게
 * 보강하면서 본문이 달라졌고, 개정 시행일은 2026-09-26으로 확정되었다.
 *
 * SIGNUP_PRIVACY_VERSION과 날짜가 같지만 상수를 합치지 않는다. 처리방침은 상시 공개하는
 * 고지 문서이고, 회원가입 수집·이용 동의는 증빙에 남는 동의 문서다. 목적도 개정 시점도
 * 달라서, 한쪽을 고칠 때 다른 쪽이 따라 움직이면 안 된다.
 *
 * 공개 고지 문서의 개정 이력을 표시하기 위한 값이며, 동의 증빙에는 쓰지 않는다.
 * 그래서 아래 areLegalVersionsConfirmed()에도 넣지 않는다(넣으면 고지 문서 사정 때문에
 * 가입 동의 저장이 막힌다).
 */
// 타입을 string으로 두는 이유는 LEGAL_EFFECTIVE_DATE와 같다. 리터럴로 좁혀지면
// UNCONFIRMED_VERSION과 비교하는 자리가 "겹치지 않는 비교"로 잡힌다.
export const PRIVACY_POLICY_VERSION: string = "2026-09-26";

/**
 * 신청 단계에서 받는 [필수] 동의(취소·환불 안내 포함)의 버전. 확정 전 자리표시자.
 *
 * 회원가입 동의(TERMS_VERSION / SIGNUP_PRIVACY_VERSION)와 목적도 개정 시점도 달라
 * 상수를 따로 둔다. 주문·상담 1건마다 그때의 버전을 증빙에 남긴다.
 *
 * ⚠️ 이 상수는 아래 areLegalVersionsConfirmed()에 넣지 않는다.
 *    넣으면 신청 문구 사정 때문에 회원가입 동의 저장까지 막힌다.
 *    반대로 회원가입 문구 사정으로 신청이 막히지도 않는다.
 *    신청을 저장해도 되는지는 isOrderConsentVersionConfirmed()로 따로 본다.
 */
export const ORDER_CONSENT_VERSION = LEGAL_EFFECTIVE_DATE;

/**
 * 신청 단계 동의를 "확정된 버전"으로 저장해도 되는 상태인지.
 *
 * 회원가입과 달리 신청 자체를 막지는 않는다. 신청을 막으면 판매가 멈추기 때문이다.
 * 대신 증빙에 자리표시자 버전이 남는 상태인지를 이 함수로 확인할 수 있게 해 둔다.
 */
export function isOrderConsentVersionConfirmed(): boolean {
  return ORDER_CONSENT_VERSION !== UNCONFIRMED_VERSION;
}

/**
 * 회원가입 동의를 저장해도 되는 상태인지.
 *
 * 증빙에 실제로 기록되는 두 버전만 본다. 처리방침 버전은 동의 대상이 아니므로
 * 여기에 넣지 않는다. 넣으면 고지 문서 사정 때문에 가입 동의 저장이 막힌다.
 *
 * 동의 증빙을 저장하는 코드는 저장 직전에 이 값을 확인해,
 * 자리표시자 버전이 DB에 기록되지 않도록 막는다.
 */
export function areLegalVersionsConfirmed(): boolean {
  return [TERMS_VERSION, SIGNUP_PRIVACY_VERSION].every(
    (version) => version !== UNCONFIRMED_VERSION,
  );
}

